"""
Builds site/js/icons.js: which character in the X-Wing icon fonts draws which icon.

    python tools/build_icons.py

Input:  data/icons/xwing-miniatures.css  (the name -> character table that ships with the
        X-Wing Miniatures Font, as used by YASB; the font is SIL Open Font License)
Output: site/js/icons.js  (window.XWING_GLYPHS = {font: {...}, ship: {...}})
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
css = (ROOT / "data" / "icons" / "xwing-miniatures.css").read_text(encoding="utf-8")

glyphs = {"font": {}, "ship": {}}
for kind, name, content in re.findall(
        r"xwing-miniatures-(font|ship)-([a-z0-9-]+):before\s*\{\s*content:\s*\"((?:\\.|[^\"])*)\"", css):
    # CSS escapes: \" \\ and \XXXX hex
    ch = re.sub(r"\\([0-9a-fA-F]{1,6})\s?", lambda m: chr(int(m.group(1), 16)), content)
    ch = re.sub(r"\\(.)", r"\1", ch)
    glyphs[kind][name] = ch

# The site's own icon names that differ from the font's names
ALIASES = {"configuration": "config", "payload": "device", "force": "forcecharge", "rotate": "rotatearc",
           "rangebonus": "rangebonusindicator"}
for ours, theirs in ALIASES.items():
    if theirs in glyphs["font"]:
        glyphs["font"][ours] = glyphs["font"][theirs]

# Ships whose YASB name differs from the font's name (variants share the same silhouette)
SHIP_ALIASES = {"delta7baethersprite": "delta7aethersprite", "btanr2wywing": "btanr2ywing",
                "cr90corelliancorvette": "cr90corvette", "tieininterceptor": "tieinterceptor"}
for ours, theirs in SHIP_ALIASES.items():
    if theirs in glyphs["ship"]:
        glyphs["ship"][ours] = glyphs["ship"][theirs]

FACTIONS = {"Rebel Alliance": "rebel", "Galactic Empire": "empire", "Scum and Villainy": "scum",
            "First Order": "firstorder", "Galactic Republic": "republic", "Separatist Alliance": "separatists",
            "Resistance": "rebel-outline"}   # the Resistance emblem is the outlined starbird
glyphs["faction"] = {f: glyphs["font"][k] for f, k in FACTIONS.items() if k in glyphs["font"]}

out = ROOT / "site" / "js" / "icons.js"
out.write_text("// Generated by tools/build_icons.py - do not edit by hand.\n"
               "window.XWING_GLYPHS = " + json.dumps(glyphs, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"{len(glyphs['font'])} icons, {len(glyphs['ship'])} ships, factions: {', '.join(glyphs['faction'])}")
