  /** The card text to display: from the curated text, or the errata's "should read" text when it is a full quote. */
  function currentText(c) {
    if (c.text) return { text: c.text, from: "card" };
    // use the most recent full-text erratum: each paragraph like
    // 'Ship ability should read: "..."' becomes one line of card text
    for (const id of [...c.errata].reverse()) {
      const e = ERRATA[id];
      const lines = [];
      let ok = true;
      const joined = e.text.join("\n").replace(/now reads:\s*\n/i, "now reads: ");
      for (const para of joined.split("\n")) {
        const m = para.match(/^(Pilot ability |Ship ability )?should read:?\s*[“"](.+?)(?:[”"]\)?\.?)?$/i)
          || para.match(/^()The ability text now reads:\s*[“"](.+?)(?:[”"]\)?\.?)?$/i);
        // reject things like: "Imperial only" in the restrictions box
        if (!m || /[“”"]/.test(m[2])) { ok = false; break; }
        const body = m[2];
        if (/^(\.\.\.|…)/.test(body) || /(\.\.\.|…)$/.test(body)) { ok = false; break; }
        lines.push((m[1] ? `**${m[1].trim()}:** ` : "") + body);
      }
      if (ok && lines.length) return { text: lines.join("\n"), from: "errata" };
    }
    return null;
  }

