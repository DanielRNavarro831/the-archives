  /** Turn stored text into safe HTML: icons, links to linked cards, "see X" rule links, search highlights. */
  function fmt(text, opts = {}) {
    let html = esc(text);
    html = html.replace(/\{([a-z-]+)\}/g, (m, k) => iconHtml(k));
    html = html.replace(/\*\*(.+?)\*\*/g, "<b>$1</b>");
    // link the first mention of each related card
    (opts.cards || []).forEach((id) => {
      const c = CARDS[id];
      if (!c || id === opts.self) return;
      const name = esc(c.name).replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
        .replace(/&quot;/g, "(?:&quot;|“|”)").replace(/&#39;/g, "(?:&#39;|’)");
      const re = new RegExp(`(^|[^\\w>])(${name})(?![\\w<])`);
      let done = false;
      html = html.replace(re, (m, pre, n) => { if (done) return m; done = true; return `${pre}<a href="#/card/${id}">${n}</a>`; });
    });
    // "see Lock" / "(see Attack)" -> rule links
    html = html.replace(/\b([Ss]ee) ([A-Z][A-Za-z’' -]{2,40}?)(?=[).,;]|$)/g, (m, see, term) => {
      const id = RULE_BY_TITLE[term.toLowerCase().trim()];
      return id ? `${see} <a href="#/rule/${id}">${term}</a>` : m;
    });
    if (opts.hl && opts.hl.length) html = highlight(html, opts.hl);
    return html;
  }

  function highlight(html, terms) {
    const parts = html.split(/(<[^>]+>)/);
    const re = new RegExp("(" + terms.map((t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")", "gi");
    return parts.map((p) => (p.startsWith("<") ? p : p.replace(re, "<mark>$1</mark>"))).join("");
  }

